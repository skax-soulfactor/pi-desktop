/** 이 Mate 홈의 설정 (기본: 실행기의 홈, MATE_HOME) */
export function mateTunables(home: string = mateHome()): TunableStore {
  return tunableStoreAt(home, MATE_TUNABLES);
}

/** 정의에 적힌 기본값 */
export function mateDefault<T extends number | string>(id: string): T {
  const def = MATE_TUNABLES.find((d) => d.id === id);
  if (!def) throw new Error(`정의되지 않은 설정 항목입니다: ${id}`);
  return def.default as T;
}
