let defaultHome: string | undefined;

/** 데몬이 시작할 때 자기 홈을 알려 둔다 (모듈 함수가 env 없이 읽을 수 있게) */
export function useDaemonHome(home: string): void {
  defaultHome = home;
}

export function daemonTunables(home: string = defaultHome ?? agentHome()): TunableStore {
  return tunableStoreAt(home, DAEMON_TUNABLES);
}

export function daemonDefault(id: string): number {
  const def = DAEMON_TUNABLES.find((d) => d.id === id);
  if (!def) throw new Error(`정의되지 않은 설정 항목입니다: ${id}`);
  return def.default as number;
}
